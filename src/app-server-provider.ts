// Protocol: generated by the pinned @openai/codex 0.165.0 app-server generate-ts.
// Keep RPC envelopes private: auth, user inputs and reasoning must never be logged.
type ObjectValue = Record<string, unknown>;
type Notification = { method:string; params:ObjectValue };
type Tokens = { accessToken:string; chatgptAccountId:string; chatgptPlanType:null };
const prefix = 'app-server:';
const maxBytes = 2_097_152;
const rpcTimeout = 30_000;
const interruptTimeout = 5_000;
// Warm stateless threads: bounded reuse so rollouts/memory of one loaded thread stay small.
const warmMaxUses = 50;
const warmMaxAgeMs = 3_600_000;
type WarmThread = {connection:Connection; id:string; key:string; uses:number; created:number};
const object = (value:unknown):ObjectValue => value && typeof value === 'object' && !Array.isArray(value) ? value as ObjectValue : {};
const failure = (code:string, message:string) => new ApiError(502, code, message);
const aborted = () => new ApiError(499, 'request_cancelled', 'Request cancelled.');
function reportedUsage(value:unknown):ProviderUsage|null {
  const record=object(value);
  const number=(key:string)=>typeof record[key]==='number'&&Number.isSafeInteger(record[key])&&(record[key] as number)>=0?record[key] as number:null;
  const input=number('inputTokens'),output=number('outputTokens');
  if(input===null||output===null)return null;
  return {input_tokens:input,output_tokens:output,cached_input_tokens:number('cachedInputTokens'),
    reasoning_output_tokens:number('reasoningOutputTokens'),...(number('cacheWriteInputTokens')!==null?{cache_write_input_tokens:number('cacheWriteInputTokens')!}:{})};
}
function turnUsage(total:ProviderUsage|null,baseline:ProviderUsage|null):ProviderUsage|null {
  if(!total||!baseline)return null;
  const difference=(key:keyof ProviderUsage)=>typeof total[key]==='number'&&typeof baseline[key]==='number'&&total[key]!>=baseline[key]! ? total[key]!-baseline[key]! : null;
  const input=difference('input_tokens'),output=difference('output_tokens');
  if(input===null||output===null)return null;
  const cacheWrite=difference('cache_write_input_tokens');
  return {input_tokens:input,output_tokens:output,cached_input_tokens:difference('cached_input_tokens'),reasoning_output_tokens:difference('reasoning_output_tokens'),...(cacheWrite!==null?{cache_write_input_tokens:cacheWrite}:{})};
}

