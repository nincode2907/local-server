async function sourceTokens(sourceHome:string):Promise<Tokens> {
  // Read the existing CLI login without copying refresh tokens or modifying auth.json.
  try {
    const path = join(sourceHome, 'auth.json');
    if ((await lstat(path)).size > 1_048_576) throw new Error('size');
    const auth = object(JSON.parse(await readFile(path, 'utf8')));
    const tokens = object(auth.tokens);
    if (typeof tokens.access_token !== 'string' || !tokens.access_token || typeof tokens.account_id !== 'string' || !tokens.account_id)
      throw new Error('missing');
    return {accessToken:tokens.access_token, chatgptAccountId:tokens.account_id, chatgptPlanType:null};
  } catch {
    throw failure('codex_auth_required', 'A ChatGPT CLI login in auth.json is required. Run codex login, then retry.');
  }
}

class Connection {
  private child:ChildProcessWithoutNullStreams;
  private sequence = 0;
  private pending = new Map<number, {resolve:(value:ObjectValue)=>void; reject:(error:Error)=>void; timer:ReturnType<typeof setTimeout>}>();
  readonly listeners = new Set<(event:Notification)=>void>();
  readonly failures = new Set<(error:Error)=>void>();
  readonly totals = new Map<string,ProviderUsage>();
  private dead = false;
  private closed:Promise<void>;
  private authenticated?:Tokens;
  private authJob?:Promise<void>;
  private processUsers = 0;
  readonly ready:Promise<void>;

  constructor(command:string, args:string[], env:Record<string,string>, cwd:string, private sourceHome:string) {
    this.child = spawn(command, args, {env, cwd, windowsHide:true});
    this.closed = new Promise(done => this.child.once('close', done));
    // Drain stderr without retaining or exposing it.
    this.child.stderr.resume();
    this.child.once('error', () => this.stop(failure('codex_app_server_unavailable', 'Could not start Codex app-server. Check CODEX_BIN and CLI compatibility.')));
    this.child.once('exit', () => this.stop(failure('codex_app_server_exited', 'Codex app-server exited. Retry the request.')));
    this.child.stdin.on('error', () => this.stop(failure('codex_app_server_io', 'Codex app-server input closed.')));
    const decoder = new StringDecoder('utf8');
    let buffer = '';
    this.child.stdout.on('data', (chunk:Buffer) => {
      if (this.dead) return;
      buffer += decoder.write(chunk);
      let newline:number;
      while ((newline = buffer.indexOf('\n')) >= 0) {
        const line = buffer.slice(0,newline); buffer = buffer.slice(newline+1);
        if (Buffer.byteLength(line) > maxBytes) { this.stop(failure('provider_event_limit', 'Provider event exceeds limit.')); return; }
        if (line.trim()) {
          try { this.receive(object(JSON.parse(line))); }
          catch { this.stop(failure('codex_app_server_protocol', 'Invalid Codex app-server event.')); return; }
        }
      }
      if (Buffer.byteLength(buffer) > maxBytes) this.stop(failure('provider_event_limit', 'Provider event exceeds limit.'));
    });
    this.child.stdout.once('end', () => this.stop(failure('codex_app_server_io', 'Codex app-server output closed.')));
    this.ready = this.request('initialize', {clientInfo:{name:'codex_local_server',title:'Codex Local Server',version:'0.1.0'},capabilities:{experimentalApi:true}})
      .then(() => { this.send({method:'initialized'}); });
    void this.ready.catch(() => {});
  }

  get alive() { return !this.dead; }
  get pid() { return this.child.pid; }
  watchProcess(callback:ObservedTurnOptions['onProcess']) {
    if (this.pid && this.processUsers++ === 0) callback?.(this.pid,true,'codex_app_server_shared_process');
    return () => { if (this.pid && --this.processUsers === 0) callback?.(this.pid,false,'codex_app_server_shared_process'); };
  }
  async waitClosed() { await this.closed; }
  private send(message:ObjectValue) {
    if (this.dead) throw failure('codex_app_server_exited', 'Codex app-server is unavailable. Retry the request.');
    this.child.stdin.write(JSON.stringify(message)+'\n');
  }
  request(method:string, params:ObjectValue, timeout=rpcTimeout):Promise<ObjectValue> {
    if (this.dead) return Promise.reject(failure('codex_app_server_exited', 'Codex app-server is unavailable. Retry the request.'));
    const id = ++this.sequence;
    return new Promise((resolveRequest,reject) => {
      const timer = setTimeout(() => this.stop(failure('codex_app_server_timeout', 'Codex app-server did not acknowledge a request.')),timeout);
      this.pending.set(id,{resolve:resolveRequest,reject,timer});
      try { this.send({id,method,params}); } catch(error) { this.stop(error as Error); }
    });
  }
  private receive(message:ObjectValue) {
    if (typeof message.method === 'string') {
      if (message.id !== undefined) { void this.serverRequest(message); return; }
      const event = {method:message.method, params:object(message.params)};
      if(event.method==='thread/tokenUsage/updated'&&typeof event.params.threadId==='string') {
        const usage=reportedUsage(object(event.params.tokenUsage).total);
        if(usage){this.totals.delete(event.params.threadId);this.totals.set(event.params.threadId,usage);}
        else this.totals.delete(event.params.threadId);
        while(this.totals.size>512)this.totals.delete(this.totals.keys().next().value!);
      }
      for (const listener of this.listeners) listener(event);
    } else if (typeof message.id === 'number') {
      const pending = this.pending.get(message.id);
      if (!pending) return;
      clearTimeout(pending.timer); this.pending.delete(message.id);
      // RPC error bodies can contain private provider/internal data; expose only a stable local code.
      if (message.error) pending.reject(failure('codex_app_server_rpc', 'Codex app-server rejected a request. Check login, model and CLI compatibility.'));
      else pending.resolve(object(message.result));
    }
  }
  private async serverRequest(message:ObjectValue) {
    try {
      if (message.method === 'account/chatgptAuthTokens/refresh') {
        const tokens = await sourceTokens(this.sourceHome);
        const previous = object(message.params).previousAccountId;
        if (!this.authenticated || tokens.accessToken === this.authenticated.accessToken || tokens.chatgptAccountId !== this.authenticated.chatgptAccountId || (previous && previous !== tokens.chatgptAccountId))
          throw failure('codex_auth_refresh_required', 'Refresh the original ChatGPT CLI login with codex login, then retry.');
        this.authenticated = tokens;
        this.send({id:message.id,result:tokens});
        return;
      }
      this.send({id:message.id,error:{code:-32601,message:'Gateway disallows server tool and approval requests.'}});
      // Unexpected execution/approval means policy parity is lost; terminate before acknowledging a tool.
      this.stop(failure('unexpected_agent_tool', 'Codex attempted an agent tool. Request rejected.'));
    } catch {
      if (this.alive) {
        this.send({id:message.id,error:{code:-32000,message:'ChatGPT CLI login needs renewal.'}});
        this.stop(failure('codex_auth_refresh_required', 'Refresh the original ChatGPT CLI login with codex login, then retry.'));
      }
    }
  }
  async authenticate() {
    if (this.authJob) return this.authJob;
    this.authJob = (async () => {
      const tokens = await sourceTokens(this.sourceHome);
      if (this.authenticated) {
        if (tokens.chatgptAccountId !== this.authenticated.chatgptAccountId)
          throw failure('codex_account_changed', 'The CLI account changed. Restart the gateway before using another account.');
        // Keep in-flight turns on the same identity. Renewal is handled by the refresh RPC.
        return;
      }
      await this.request('account/login/start',{type:'chatgptAuthTokens',...tokens});
      this.authenticated = tokens;
    })();
    try { await this.authJob; } finally { this.authJob = undefined; }
  }
  stop(error:Error) {
    if (this.dead) return;
    this.dead = true; this.authenticated = undefined;
    for (const pending of this.pending.values()) {clearTimeout(pending.timer); pending.reject(error);}
    this.pending.clear();
    for (const listener of this.failures) listener(error);
    this.listeners.clear(); this.failures.clear();
    this.child.stdin.destroy();
    this.child.kill();
  }
  async close() {
    this.stop(failure('codex_app_server_closed', 'Codex app-server closed.'));
    await this.closed;
  }
}

class AppServerProvider implements Provider {
  private connection?:Connection;
  private connecting?:Promise<Connection>;
  private closed = false;
  private connections = new Set<Connection>();
  private locks = new Set<string>();
  private warm:WarmThread[] = [];
  private egressJob?:Promise<EgressForwarder|null>;
  constructor(private config:Config, private runtime:string, private home:string, private egressFactory?:EgressFactory) {}
  /** One forwarder per provider, shared by app-server restarts; null means direct egress. */
  private forwarder() { return this.egressJob ??= openEgress(this.config.codexEgressForwarder ?? false, this.egressFactory); }
  private egressHandle:EgressForwarder|null = null;
  egress() { return this.egressHandle ? {enabled:true,...this.egressHandle.snapshot()} : null; }
  canResume(id:string) { return id.startsWith(prefix); }
  start(model:string, effort?:ChatRequest['reasoning_effort'], ephemeral=false, options:{stateless?:boolean}={}):ProviderThread {
    // Only stateless, non-ephemeral threads are recyclable: sessions own their thread
    // and Codex refuses thread/revert on ephemeral (playground) threads.
    return new AppServerThread(this,model,effort,null,ephemeral,Boolean(options.stateless)&&!ephemeral&&this.warmLimit>0);
  }
  resume(id:string,model:string,effort?:ChatRequest['reasoning_effort']):ProviderThread {
    if (!this.canResume(id)) throw failure('codex_transport_mismatch', 'Restore saved gateway history before changing the Codex transport.');
    return new AppServerThread(this,model,effort,id.slice(prefix.length),false,false);
  }
  get warmLimit() { return this.config.codexWarmThreads ?? 0; }
  warmKey(model:string,effort?:ChatRequest['reasoning_effort']) { return JSON.stringify([model,effort??null]); }
  /** Take an idle warm thread of this connection, never waiting: the caller starts a new thread when none is idle. */
  takeWarm(key:string,connection:Connection):WarmThread|undefined {
    const now=Date.now();
    for (const entry of [...this.warm]) {
      const usable=entry.connection===connection&&connection.alive&&entry.uses<warmMaxUses&&now-entry.created<warmMaxAgeMs;
      if (!usable) { this.warm.splice(this.warm.indexOf(entry),1); void this.retire(entry); continue; }
      if (entry.key!==key || this.locks.has(entry.id)) continue;
      this.warm.splice(this.warm.indexOf(entry),1);
      return entry;
    }
    return undefined;
  }
  /**
   * After a completed stateless turn, revert the thread to an empty history and
   * prove it is empty before another request may use it. Any doubt retires it.
   */
  async recycle(entry:WarmThread,turnId:string,release:()=>void) {
    const {connection,id}=entry;
    try {
      if (this.closed || !connection.alive || entry.uses>=warmMaxUses || Date.now()-entry.created>=warmMaxAgeMs) throw new Error('retire');
      await connection.request('thread/revert',{threadId:id,beforeTurnId:turnId});
      const listed=await connection.request('thread/turns/list',{threadId:id,limit:1});
      if (!Array.isArray(listed.data) || listed.data.length!==0) throw new Error('not empty');
      // Cumulative usage of an empty history is zero; never subtract a stale pre-revert total.
      connection.totals.delete(id);
      if (this.closed || !connection.alive || this.warm.length>=this.warmLimit) throw new Error('retire');
      this.warm.push(entry);
    } catch {
      await this.retire(entry);
    } finally { release(); }
  }
  private async retire(entry:WarmThread) {
    if (!entry.connection.alive) return;
    // Unsubscribe bounds loaded thread lifetimes. It never archives/deletes native data.
    try { await entry.connection.request('thread/unsubscribe',{threadId:entry.id}); } catch {/* best effort */}
  }
  async warmup() { await this.connect(); }
  get reused() { return Boolean(this.connection?.alive); }
  async connect():Promise<Connection> {
    if (this.closed) throw failure('codex_app_server_closed','Codex provider is closed.');
    if (this.connection?.alive) return this.connection;
    if (this.connecting) return this.connecting;
    this.connecting = (async () => {
      await mkdir(this.home,{recursive:true,mode:0o700});
      const sourceHome=resolve(process.env.CODEX_HOME ?? join(homedir(),'.codex'));
      if ((await lstat(this.home)).isSymbolicLink() || (await realpath(this.home)).toLowerCase() === (await realpath(sourceHome).catch(()=>sourceHome)).toLowerCase())
        throw failure('codex_app_server_config','Gateway Codex home must be separate from the original Codex home.');
      // This is a gateway-owned home, never the source CODEX_HOME. Refuse added config
      // rather than silently loading rules, hooks, environments or integrations.
      for (const name of ['config.toml','AGENTS.md','rules','hooks','plugins','environments.toml']) {
        try { await lstat(join(this.home,name)); }
        catch(error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') continue; throw error; }
        throw failure('codex_app_server_config', 'Gateway Codex home contains unexpected configuration. Remove it before retrying.');
      }
      // Codex creates skills/.system itself on first launch, even with skills
      // disabled. Allow only that native directory; reject custom skill roots.
      const skills=join(this.home,'skills');
      try {
        const stat=await lstat(skills);
        if (!stat.isDirectory() || stat.isSymbolicLink()) throw failure('codex_app_server_config','Gateway Codex home contains unexpected skills configuration.');
        for (const name of await readdir(skills)) {
          const entry=await lstat(join(skills,name));
          if (name!=='.system' || !entry.isDirectory() || entry.isSymbolicLink()) throw failure('codex_app_server_config','Gateway Codex home contains unexpected skills configuration.');
        }
      } catch(error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
      const require = createRequire(import.meta.url);
      // Launch the pinned native executable directly: no Node launcher to orphan
      // its child when Windows terminates the parent process.
      const architecture = process.arch==='x64'?'x86_64':process.arch==='arm64'?'aarch64':undefined;
      const target = process.platform==='win32'?'pc-windows-msvc':process.platform==='darwin'?'apple-darwin':process.platform==='linux'?'unknown-linux-musl':undefined;
      if (!this.config.codexBin && (!architecture || !target)) throw failure('codex_app_server_unavailable','Unsupported Codex CLI platform.');
      const packageName=`@openai/codex-${process.platform}-${process.arch}`;
      const packageRoot=()=>dirname(require.resolve(`${packageName}/package.json`));
      const override = this.config.codexBin ? resolve(this.config.codexBin) : undefined;
      const nodeScript = override && ['.js','.mjs','.cjs'].includes(extname(override));
      const command = nodeScript ? process.execPath : override ?? join(packageRoot(),'vendor',`${architecture}-${target}`,'bin',process.platform==='win32'?'codex.exe':'codex');
      const args = [...(nodeScript?[override!]:[]),'app-server','--listen','stdio://',
        ...Object.entries(policy).flatMap(([key,value]) => ['-c',`${key}=${JSON.stringify(value)}`])];
      const env:Record<string,string> = {PATH:process.env.PATH ?? '',HOME:homedir(),CODEX_HOME:this.home};
      for (const key of ['TMPDIR','TEMP','TMP','LANG','SSL_CERT_FILE','SSL_CERT_DIR','SYSTEMROOT','WINDIR','COMSPEC','PATHEXT','USERPROFILE','APPDATA','LOCALAPPDATA'])
        if (process.env[key]) env[key] = process.env[key]!;
      // Proxy variables are never inherited; they only point at the gateway-owned forwarder.
      const forwarder = await this.forwarder();
      this.egressHandle = forwarder;
      Object.assign(env, egressEnv(forwarder));
      const connection = new Connection(command,args,env,this.runtime,sourceHome);
      this.connections.add(connection);
      void connection.waitClosed().then(()=>this.connections.delete(connection));
      try { await connection.ready; }
      catch(error) { await connection.close(); this.connections.delete(connection); throw error; }
      if (this.closed) {await connection.close(); throw failure('codex_app_server_closed','Codex provider is closed.');}
      this.connection = connection;
      return connection;
    })();
    try {return await this.connecting;} finally {this.connecting=undefined;}
  }
  settings(model:string,effort?:ChatRequest['reasoning_effort']) {
    return {model,cwd:this.runtime,approvalPolicy:'never',sandbox:'read-only',baseInstructions:gatewayInstructions,
      developerInstructions:'',config:{...policy,...(effort?{model_reasoning_effort:effort}:{})}};
  }
  lock(id:string) {
    if (this.locks.has(id)) throw failure('codex_thread_busy','A turn is already running for this Codex thread.');
    this.locks.add(id);
    return () => this.locks.delete(id);
  }
  async close() {
    this.closed = true;
    this.warm = [];
    await this.connecting?.catch(() => {});
    await Promise.all([...this.connections].map(connection=>connection.close()));
    this.connections.clear();
    await (await this.egressJob?.catch(() => null))?.close();
    await rm(this.runtime,{recursive:true,force:true});
  }
}

class AppServerThread implements ProviderThread {
  private busy = false;
  constructor(private provider:AppServerProvider, private model:string, private effort:ChatRequest['reasoning_effort']|undefined, private rawId:string|null, private ephemeral:boolean, private recyclable:boolean) {}
  get id() { return this.rawId ? prefix+this.rawId : null; }
  async run(input:string,options:ObservedTurnOptions={}):Promise<ProviderTurn> {
    if (this.busy) throw failure('codex_thread_busy','A turn is already running for this Codex thread.');
    this.busy = true;
    let unlock:(()=>void)|undefined;
    let connection:Connection|undefined;
    let listener:((event:Notification)=>void)|undefined;
    let failed:((error:Error)=>void)|undefined;
    let abort:(()=>void)|undefined;
    let cancelTimer:ReturnType<typeof setTimeout>|undefined;
    let releaseProcess:(()=>void)|undefined;
    let turnId:string|undefined;
    let turnError:Error|undefined;
    let completed = false;
    let warm:WarmThread|undefined;
    let usage:ProviderUsage|null = null;
    const texts = new Map<string,string>();
    const items = new Map<string,ThreadItem>();
    let finalResponse = '';
    const started = performance.now();
    const timing:AppServerLifecycleTiming = {connection_reused:this.provider.reused,shared_process:true,connection_ready_ms:null,thread_ready_ms:null,turn_started_ms:null,first_delta_ms:null,turn_completed_ms:null,provider_returned_ms:null};
    const mark = (key:'connection_ready_ms'|'thread_ready_ms'|'turn_started_ms'|'first_delta_ms'|'turn_completed_ms'|'provider_returned_ms') => {timing[key] = performance.now()-started;options.onAppServerLifecycle?.({...timing});};
    try {
      if (options.signal?.aborted) throw aborted();
      if (this.rawId) unlock = this.provider.lock(this.rawId);
      await options.observe?.({stdin:input,instructions:gatewayInstructions,output_schema:options.outputSchema??null,
        model:this.model,reasoning_effort:this.effort??null,thread_id:this.id,ephemeral:this.ephemeral,transport:'app-server-stdio',
        policy:{sandbox:'read-only',approval:'never',network:false,agent_tools:false,ignore_user_config:true,ignore_rules:true,isolation:'dedicated_codex_home'},
        internal_context:{provenance:'Internal / unavailable',available:false,description:'Private provider context and resumed history are not exposed.'}});
      connection = await this.provider.connect();
      if (options.signal?.aborted) throw aborted();
      await connection.authenticate();
      mark('connection_ready_ms');
      if (options.signal?.aborted) throw aborted();
      releaseProcess=connection.watchProcess(options.onProcess);
      const settings = this.provider.settings(this.model,this.effort);
      const resuming=Boolean(this.rawId);
      const key=this.provider.warmKey(this.model,this.effort);
      // A warm thread passed the same admission checks below when it was created and
      // was verified empty after its previous turn; turn/start re-asserts policy per turn.
      warm=this.recyclable&&!this.rawId?this.provider.takeWarm(key,connection):undefined;
      if (warm) {
        this.rawId=warm.id;unlock=this.provider.lock(this.rawId);timing.thread_reused=true;
      } else {
        const response = await connection.request(this.rawId?'thread/resume':'thread/start',this.rawId
          ?{...settings,threadId:this.rawId,excludeTurns:true}
          :{...settings,allowProviderModelFallback:false,ephemeral:this.ephemeral,environments:[],dynamicTools:[]});
        const thread = object(response.thread);
        if (typeof thread.id !== 'string' || !thread.id || (this.rawId && this.rawId !== thread.id))
          throw failure('missing_thread_id','Codex did not return the expected thread ID.');
        this.rawId = thread.id;
        if (!unlock) unlock = this.provider.lock(this.rawId);
        const sandbox = object(response.sandbox);
        if (response.approvalPolicy !== 'never' || sandbox.type !== 'readOnly' || sandbox.networkAccess !== false || !Array.isArray(response.instructionSources) || response.instructionSources.length)
          throw failure('codex_app_server_policy','Codex app-server did not preserve gateway permissions or instruction isolation.');
        if (this.ephemeral && thread.ephemeral !== true)
          throw failure('codex_app_server_policy','Codex app-server did not preserve ephemeral mode.');
        if (this.recyclable && !resuming) {
          if (thread.ephemeral === true) this.recyclable=false;
          else warm={connection,id:this.rawId,key,uses:0,created:Date.now()};
        }
        if (warm) timing.thread_reused=false;
      }
      mark('thread_ready_ms');
      if (options.signal?.aborted) throw aborted();
      const current = connection;
      // total is cumulative across the thread; last covers only the latest model
      // request and can undercount a multi-request turn. Subtract a known baseline.
      // On resume after process restart without a baseline, usage stays unknown.
      const baseline=current.totals.get(this.rawId)??(resuming?null:{input_tokens:0,output_tokens:0,cached_input_tokens:0,reasoning_output_tokens:0,cache_write_input_tokens:0});
      if(warm)warm.uses++;
      let settle!:()=>void;
      let reject!:(error:Error)=>void;
      const terminal = new Promise<void>((done,fail) => {settle=done;reject=fail;});
      void terminal.catch(() => {});
      let outputBytes=0;
      const rememberText=(id:string,text:string)=>{
        const bytes=outputBytes-Buffer.byteLength(texts.get(id)??'')+Buffer.byteLength(text);
        if(bytes>maxBytes || (!texts.has(id)&&texts.size>=512))throw failure('provider_event_limit','Provider output exceeds limit.');
        texts.set(id,text);outputBytes=bytes;
      };
      const publicItem = (value:unknown) => {
        const item = object(value);
        const allowed = ['userMessage','agentMessage','reasoning'];
        if (typeof item.type !== 'string' || !allowed.includes(item.type))
          throw failure('unexpected_agent_tool','Codex attempted an agent tool. Request rejected.');
        if (item.type !== 'agentMessage') return;
        if (typeof item.id !== 'string' || typeof item.text !== 'string') throw failure('codex_app_server_protocol','Invalid public assistant message.');
        rememberText(item.id,item.text);
        items.set(item.id,{id:item.id,type:'agent_message',text:item.text});
        finalResponse=item.text;
        options.onEvent?.({type:'output',item_id:item.id,text:item.text});
      };
      const interrupt = () => {
        if (completed) return;
        cancelTimer??=setTimeout(()=>current.stop(failure('codex_interrupt_timeout','Codex did not stop the cancelled turn. Shared app-server terminated.')),interruptTimeout);
        if(!turnId || interruptSent)return;
        interruptSent=true;
        void current.request('turn/interrupt',{threadId:this.rawId,turnId},interruptTimeout).catch(error=>current.stop(error));
      };
      let interruptSent=false;
      abort=()=>{turnError=aborted();interrupt();};
      failed=error=>{turnError=error;reject(error);};
      listener=event=>{
        const p=event.params;
        if (p.threadId !== this.rawId) return;
        try {
          if (event.method==='turn/started') {
            const id=object(p.turn).id;
            if (typeof id!=='string' || (turnId && turnId!==id)) throw failure('codex_app_server_protocol','Unexpected turn ID.');
            turnId=id;if(timing.turn_started_ms===null)mark('turn_started_ms');if(options.signal?.aborted)interrupt();
            return;
          }
          const eventTurnId=event.method==='turn/completed'?object(p.turn).id:p.turnId;
          if (!turnId || eventTurnId!==turnId) return;
          if (event.method==='item/started' || event.method==='item/completed') publicItem(p.item);
          else if (event.method==='item/agentMessage/delta') {
            if(options.signal?.aborted)return;
            if(typeof p.itemId!=='string'||typeof p.delta!=='string')throw failure('codex_app_server_protocol','Invalid assistant delta.');
            const text=(texts.get(p.itemId)??'')+p.delta;
            rememberText(p.itemId,text);
            items.set(p.itemId,{id:p.itemId,type:'agent_message',text});
            finalResponse=text;
            if(p.delta && timing.first_delta_ms===null)mark('first_delta_ms');
            options.onEvent?.({type:'output',item_id:p.itemId,text});
          } else if (event.method==='thread/tokenUsage/updated') {
            usage=turnUsage(reportedUsage(object(p.tokenUsage).total),baseline);
            if(usage)options.onEvent?.({type:'usage',usage});
          } else if (event.method==='error' && p.willRetry !== true) {
            turnError=failure('codex_turn_failed','Codex turn failed. Check login and model availability.');
          } else if (event.method==='turn/completed') {
            const turn=object(p.turn);
            if(Array.isArray(turn.items))for(const item of turn.items)publicItem(item);
            completed=true;mark('turn_completed_ms');clearTimeout(cancelTimer);
            if(turn.status!=='completed')turnError??=failure('codex_turn_failed','Codex turn failed or was interrupted.');
            settle();
          }
        } catch(error) {
          turnError=error as Error;
          // Fail closed on tool execution/protocol loss. No turn on this process is replayed.
          current.stop(turnError);reject(turnError);
        }
      };
      current.listeners.add(listener);current.failures.add(failed);
      options.signal?.addEventListener('abort',abort,{once:true});
      if(options.signal?.aborted)throw aborted();
      const turnResponse=await current.request('turn/start',{threadId:this.rawId,input:[{type:'text',text:input,text_elements:[]}],
        model:this.model,...(this.effort?{effort:this.effort}:{}),approvalPolicy:'never',sandboxPolicy:{type:'readOnly',networkAccess:false},
        environments:[],...(options.outputSchema?{outputSchema:options.outputSchema}:{})});
      const returnedTurn=object(turnResponse.turn);
      if(typeof returnedTurn.id!=='string' || (turnId&&turnId!==returnedTurn.id)) {
        current.stop(failure('codex_app_server_protocol','Unexpected turn acknowledgement.'));
        throw failure('codex_app_server_protocol','Unexpected turn acknowledgement.');
      }
      turnId=returnedTurn.id;if(timing.turn_started_ms===null)mark('turn_started_ms');
      if(options.signal?.aborted)interrupt();
      await terminal;
      if(options.signal?.aborted)throw aborted();
      if(turnError)throw turnError;
      return {items:[...items.values()],finalResponse,usage};
    } catch(error) {
      turnError=error as Error;
      // If turn admission failed after turn/started, do not leave inference alive
      // while the gateway releases its scheduler slot.
      if(connection?.alive&&turnId&&!completed)connection.stop(failure('codex_turn_incomplete','Codex turn did not reach a terminal state. Shared app-server terminated.'));
      throw error;
    } finally {
      clearTimeout(cancelTimer);
      if(abort)options.signal?.removeEventListener('abort',abort);
      if(connection && listener)connection.listeners.delete(listener);
      if(connection && failed)connection.failures.delete(failed);
      releaseProcess?.();
      if(warm&&connection?.alive&&completed&&!turnError&&turnId&&!options.signal?.aborted&&warm.connection===connection&&warm.id===this.rawId) {
        // Recycle in the background: the response is not delayed, and the thread stays
        // locked (unavailable to any other request) until it is proven empty.
        const done=unlock;unlock=undefined;
        void this.provider.recycle(warm,turnId,()=>done?.());
      } else if(connection?.alive && this.rawId) {
        // Unsubscribe bounds loaded thread lifetimes. It never archives/deletes native data.
        try {await connection.request('thread/unsubscribe',{threadId:this.rawId});} catch {/* No inference retry/fallback. */}
      }
      unlock?.();this.busy=false;
      await options.observeResponse?.({final_response:finalResponse,assistant_messages:[...items.values()],usage,thread_id:this.id,
        complete:completed&&!turnError,error_code:turnError instanceof ApiError?turnError.code:turnError?'codex_error':null,
        internal_reasoning:{provenance:'Internal / unavailable',available:false,reason:'Private reasoning, auth and stderr are never recorded.'}});
      if(completed&&!turnError)mark('provider_returned_ms');
    }
  }
}

export async function createAppServerProvider(config:Config,hooks:{egress?:EgressFactory}={}):Promise<Provider> {
  const runtime=await mkdtemp(join(tmpdir(),'codex-gateway-'));
  return new AppServerProvider(config,runtime,join(config.dataDir,'codex-app-server'),hooks.egress);
}
